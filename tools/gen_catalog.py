#!/usr/bin/env python3
"""Write firmware/src/game/CatalogData.h from tools/catalog.py, so the Deck and the
balance simulator always share one catalog: names, numbers, flavor and unlocks.

    python3 tools/gen_catalog.py

Relic effects aren't data. They're ported by hand in firmware/src/game/Rules.h, and
firmware/test/test_parity checks them against the simulator's on thousands of sales.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import catalog as K  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "src", "game", "CatalogData.h")

RARITIES = ["common", "uncommon", "rare", "legendary"]
SCHOOLS = sorted({d["school"] for d in K.RELICS.values()})
# The names players see for a few habits (schools). The keys stay as they are:
# their order is part of the save format.
HABIT_NAMES = {"money": "Tokens", "routine": "Refrain", "timing": "Tempo"}
WARDS = K.WARDS

# Every stat or record an unlock can ask about. Order is part of the save format: only append.
STATS = [
    "visit_nexus", "max_networks", "big_sale_nexus", "hollow_sales", "hollows_one_run", "ward_changes_night",
    "hearth_sales", "new_wells_run", "new_wells_night", "unique_wells", "same_well_nights", "glyphs_total",
    "ember_sold", "tide_sold", "gale_sold", "hush_sold", "static_sold", "attunes_run", "attune_level",
    "kinds_night", "hidden_found", "channels_seen", "one_visit_close", "fast_closes", "nights_paid", "max_coin",
    "sales_total", "big_units", "dowses", "low_battery_close", "wins", "broke_shop", "op_nights", "loans",
    "rares_bought", "editions_owned", "relics_sold", "omens_seen", "spells_cast", "rares_one_run",
    "loans_repaid", "callings_won", "win_with", "school_win", "pact_win", "bought_total", "standing_hedge",
    "standing_hearth", "standing_warded", "eclipses_survived", "overnight_best", "summoned", "polishes",
    "portents", "candles", "mercies", "warden_escapes", "jobs_done",
]
# Stats that hold a best value (a record) rather than a running total.
BEST = {"max_networks", "big_sale_nexus", "hollows_one_run", "ward_changes_night", "new_wells_run",
        "new_wells_night", "attune_level", "kinds_night", "fast_closes", "max_coin", "big_units",
        "rares_one_run", "editions_owned", "attunes_run", "standing_hedge", "standing_hearth",
        "standing_warded", "overnight_best", "same_well_nights", "eclipses_survived"}

# The Grimoire's pages have their unlock in words only in catalog.py; here they are as stats.
GRIMOIRE_COND = [("none", 0), ("nights_paid", 10), ("bought_total", 25), ("standing_hedge", 80),
                 ("standing_hearth", 80), ("standing_warded", 80), ("loans_repaid", 1), ("unique_wells", 100),
                 ("eclipses_survived", 4), ("overnight_best", 5), ("summoned", 1), ("pact_win", 8)]


# The Deck's font is plain ASCII, so the catalog's few typographic characters
# are swapped for ASCII ones.
ASCII = {"\u00d7": "x", "\u2013": "-", "\u2014": "-", "\u2019": "'", "\u2018": "'", "\u201c": '"',
         "\u201d": '"', "\u2026": "...", "\u00e9": "e"}


def c(s):
    """A C string literal, in plain ASCII."""
    for k, v in ASCII.items():
        s = s.replace(k, v)
    bad = [ch for ch in s if ord(ch) > 126]
    if bad:
        raise SystemExit("non-ASCII %r in %r: add it to ASCII" % (bad[0], s))
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ident(s):
    return "".join(ch if ch.isalnum() else "_" for ch in s)


def unlock_fields(u):
    """(stat, need, arg, text) for an unlock tuple, or a 'start' marker."""
    if u is None:
        return "Stat::None", 0, -1, '""'
    key, need, text = u
    if key not in STATS:
        raise SystemExit("unknown unlock stat %r: add it to STATS" % key)
    arg = -1
    if key == "win_with":
        arg, need = list(K.RELICS).index(need), 1
    elif key == "school_win":
        arg, need = SCHOOLS.index(need), 1
    return "Stat::" + ident(key), int(need), arg, c(text)


def main():
    o = []
    w = o.append
    w("#pragma once")
    w("// Generated by tools/gen_catalog.py from tools/catalog.py. Don't edit by hand.")
    w("#include <stdint.h>")
    w("")
    w("namespace Cat {")
    w("")
    w("enum class Stat : uint8_t { None, %s, Count };" % ", ".join(ident(s) for s in STATS))
    w("inline const char* const StatKeys[] = {\"none\", %s};" % ", ".join(c(s) for s in STATS))
    w("inline constexpr bool StatIsBest[] = {false, %s};" % ", ".join("true" if s in BEST else "false" for s in STATS))
    w("")
    w("enum class School : uint8_t { %s, Count };" % ", ".join(ident(s.capitalize()) for s in SCHOOLS))
    w("inline const char* const SchoolNames[] = {%s};" % ", ".join(c(HABIT_NAMES.get(s, s.capitalize())) for s in SCHOOLS))
    w("enum Rarity : uint8_t { Common, Uncommon, Rare, Legendary };")
    w("inline const char* const RarityNames[] = {\"COMMON\", \"UNCOMMON\", \"RARE\", \"LEGENDARY\"};")
    w("")
    w("struct RelicDef {")
    w("  const char* key; const char* name; uint8_t rarity; uint8_t school; uint8_t phase;")
    w("  const char* text; const char* flavor;")
    w("  Stat unlock; int32_t need; int16_t arg; const char* unlockText;")
    w("  uint8_t suits;   // bit per ward that suits it (hollow, fringe, ward, nexus); 0xF = all")
    w("  bool cursed, legendary, hasFn;")
    w("};")
    w("enum Relic : uint8_t {")
    for k in K.RELICS:
        w("  R_%s," % k)
    w("  RelicCount")
    w("};")
    w("inline const RelicDef Relics[RelicCount] = {")
    for k, d in K.RELICS.items():
        st, need, arg, txt = unlock_fields(d["unlock"])
        suits = 0xF if d["suits"] == "all" else sum(1 << WARDS.index(x) for x in d["suits"].split())
        w("  {%s, %s, %d, %d, %d, %s, %s, %s, %d, %d, %s, 0x%X, %s, %s, %s}," % (
            c(k), c(d["name"]), RARITIES.index(d["rarity"]), SCHOOLS.index(d["school"]), d["phase"],
            c(d["text"]), c(d["flavor"]), st, need, arg, txt, suits,
            "true" if d["cursed"] else "false", "true" if d["legendary"] else "false",
            "true" if d["fn"] else "false"))
    w("};")
    w("")

    def simple(name, items, fields):
        """A table of (key, name, text[, flavor], unlock) style tuples."""
        w("struct %sDef { const char* key; %s };" % (name, " ".join(f[1] for f in fields)))
        w("enum %s : uint8_t {" % name)
        for k in items:
            w("  %s_%s," % (name, ident(k)))
        w("  %sCount" % name)
        w("};")
        w("inline const %sDef %ss[%sCount] = {" % (name, name, name))
        for k, v in items.items():
            w("  {%s, %s}," % (c(k), ", ".join(f[2](v) for f in fields)))
        w("};")
        w("")

    unl = lambda i: (lambda v: "%s, %d, %s" % (unlock_fields(v[i])[0], unlock_fields(v[i])[1], unlock_fields(v[i])[3]))
    simple("Trinket", K.TRINKETS, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1])),
        ("flavor", "const char* flavor;", lambda v: c(v[2])),
        ("unlock", "Stat unlock; int32_t need; const char* unlockText;", unl(3))])
    simple("Spell", K.SPELLS, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1])),
        ("flavor", "const char* flavor;", lambda v: c(v[2])),
        ("unlock", "Stat unlock; int32_t need; const char* unlockText;", unl(3)),
        ("weight", "float weight;", lambda v: "%sf" % repr(float(v[4])))])
    simple("Glyph", K.GLYPHS, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1])),
        ("flavor", "const char* flavor;", lambda v: c(v[2]))])
    simple("Edition", K.EDITIONS, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1])),
        ("p", "float chance;", lambda v: "%sf" % repr(float(v[2])))])
    mods = list(K.MODS)
    simple("Mod", K.MODS, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1])),
        ("needs", "int8_t needs;", lambda v: str(mods.index(v[2]) if v[2] else -1))])
    simple("Portent", K.PORTENTS, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1]))])
    simple("Omen", K.OMENS, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1]))])
    simple("Eclipse", K.ECLIPSES, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1]))])
    callings = {k: v for k, v in K.CALLINGS.items()}
    simple("Calling", callings, [
        ("name", "const char* name;", lambda v: c(v[0])), ("text", "const char* text;", lambda v: c(v[1])),
        ("unlock", "Stat unlock; int32_t need; const char* unlockText;", unl(2))])

    w("struct PactDef { const char* name; const char* text; };")
    w("constexpr int PactCount = %d;" % len(K.PACTS))
    w("inline const PactDef Pacts[PactCount] = {%s};" % ", ".join("{%s, %s}" % (c(a), c(b)) for a, b in K.PACTS))
    w("struct ChallengeDef { const char* name; const char* text; };")
    w("constexpr int ChallengeCount = %d;" % len(K.CHALLENGES))
    w("inline const ChallengeDef Challenges[ChallengeCount] = {%s};" % ", ".join(
        "{%s, %s}" % (c(a), c(b)) for a, b in K.CHALLENGES))
    w("struct PageDef { const char* title; const char* unlockText; const char* theme; Stat unlock; int32_t need; };")
    w("constexpr int PageCount = %d;" % len(K.GRIMOIRE))
    w("inline const PageDef Pages[PageCount] = {")
    for (title, text, theme), (st, need) in zip(K.GRIMOIRE, GRIMOIRE_COND):
        w("  {%s, %s, %s, Stat::%s, %d}," % (c(title), c(text), c(theme), ident(st) if st != "none" else "None", need))
    w("};")
    w("")
    # A fingerprint of everything a save refers to by number: if the catalog's order changes, old
    # saves would point at the wrong items, so Save.h refuses saves made with another catalog.
    import zlib
    keys = (list(K.RELICS) + list(K.TRINKETS) + list(K.SPELLS) + list(K.GLYPHS) + list(K.EDITIONS) +
            list(K.MODS) + list(K.PORTENTS) + list(K.OMENS) + list(K.ECLIPSES) + list(K.CALLINGS) + STATS +
            [p[0] for p in K.PACTS] + [ch[0] for ch in K.CHALLENGES] + [g[0] for g in K.GRIMOIRE] + SCHOOLS)
    w("// Changes whenever anything a save refers to by number is added, removed or reordered.")
    w("constexpr uint32_t CatalogHash = 0x%08Xu;" % (zlib.crc32("|".join(keys).encode()) & 0xFFFFFFFF))
    w("")
    w("} // namespace Cat")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(o) + "\n")
    print("wrote %s: %d relics, %d stats" % (os.path.normpath(OUT), len(K.RELICS), len(STATS)))


if __name__ == "__main__":
    main()
