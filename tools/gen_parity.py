#!/usr/bin/env python3
"""Random sales scored by the balance simulator, written as a test for the Deck's own
rules (firmware/test/test_parity). If the two ever disagree, one of them has a bug.

    python3 tools/gen_parity.py [count]
"""
import os
import random
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import balance_sim as B  # noqa: E402
import catalog as K  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "test", "test_parity",
                   "vectors.h")
RELICS = list(K.RELICS)
EDS = list(K.EDITIONS)
GLYPHS = list(K.GLYPHS)
OMENS = list(K.OMENS)
ECLS = list(K.ECLIPSES)
CALLINGS = list(K.CALLINGS)
FACTIONS = ["hedge", "hearth", "warded", "syndicate"]
GROWING = ["picket_fence", "pilgrims_staff", "black_ledger", "patience", "tally_stick", "ritual_candle",
           "piggy_bank", "long_receipt", "locked_diary"]


def one(rng):
    k = rng.randint(1, 7)
    ids = rng.sample(RELICS, k)
    if rng.random() < 0.15:   # make copycat and overtone show up often enough to test
        ids[0] = rng.choice(["copycat_sigil", "overtone", "keystone"])
        ids = list(dict.fromkeys(ids))
    relics = [dict(id=i, ed=(rng.choice(EDS) if rng.random() < 0.25 else None), withered=None,
                   tier=(rng.randint(0, 3) if rng.random() < 0.5 else 0)) for i in ids]
    e = rng.choice(K.ENERGIES)
    r = dict(relics=relics, calling=rng.choice(CALLINGS), veil=rng.random() < 0.1,
             trinkets=["pickpocket"] if rng.random() < 0.2 else [],
             state={g: rng.choice([0, round(rng.uniform(0, 3), 2)]) for g in GROWING},
             hollows_tonight=rng.randint(0, 6), new_wells=float(rng.randint(0, 40)),
             kinds_tonight=set(rng.sample(K.ENERGIES, rng.randint(0, 5))), heat=round(rng.uniform(0, 4), 1),
             night=rng.randint(0, 9), sales=rng.randint(0, 60), coin=float(rng.randint(0, 80)),
             crown_ban=rng.choice(K.ENERGIES), standing=defaultdict(float), pact=0, mods=set(),
             new_tonight=rng.randint(0, 8))
    r["standing"]["hearth"] = rng.choice([0.0, float(rng.randint(-20, 100))])
    r["_slots"], r["_used"] = B.relic_slots(r), B.slots_used(r)
    n = rng.choice([1, 2, 3, 5, 8, 12, 20, 30, 45])
    c = dict(e=e, units=float(rng.choice([4, 5, 6, 7, 8, 10, 12])) * rng.choice([1, 0.85, 1.2, 1.4]),
             price=round(B.BASE_PRICE[e] * rng.uniform(0.8, 1.25), 3), mult=1.0 + rng.randint(0, 4),
             x=1.0, repeats=0, coin=0.0, n=n, ward=K.WARDS[0 if n <= 3 else 1 if n <= 10 else 2 if n <= 25 else 3],
             faction=rng.choice(FACTIONS), hidden=rng.random() < 0.2, channel=rng.randint(1, 13),
             ch11=rng.randint(0, 8), strong=rng.random() < 0.35, mesh=rng.choice([0, 0, 0, 2, 3]),
             revisit=rng.random() < 0.4, nights_seen=rng.randint(1, 6), new=rng.random() < 0.4,
             ward_changed=rng.random() < 0.4, wards_tonight=rng.randint(1, 5),
             glyph=rng.choice(GLYPHS) if rng.random() < 0.3 else None, noise=round(rng.random(), 2),
             still=rng.random() < 0.5, battery_low=rng.random() < 0.1, dowsed=rng.random() < 0.2,
             one_kind=rng.random() < 0.5, hold_kinds=rng.randint(1, 4), lvl=rng.randint(0, 5),
             vi=rng.randint(0, 11), last_e=rng.choice(K.ENERGIES + [None]), ghost=rng.random() < 0.1)
    nx = dict(omen=rng.choice(OMENS) if rng.random() < 0.5 else None,
              eclipse=rng.choice(ECLS) if rng.random() < 0.3 else None, fade_e=rng.choice(K.ENERGIES), sleeping=None)
    nx["no_polish"] = nx["eclipse"] == "sleep"
    res, coin = B.score(dict(c), r, nx)
    return r, c, nx, res, coin


def b(v):
    return "1" if v else "0"


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 3000
    rng = random.Random(20261028)
    lines = ["// Generated by tools/gen_parity.py: sales scored by tools/balance_sim.py.", "#pragma once",
             "struct V { int nr; int rel[8]; int ed[8]; int tier[8]; int calling; int veil; int pickpocket;",
             "  double state[9]; int hollows; double newWells; int kinds; double heat; int night; int sales;",
             "  double coin; int crownBan; int e; double units, price, mult; int n, ward, faction, hidden, channel,",
             "  ch11, strong, mesh, revisit, nightsSeen, isNew, wardChanged, wardsTonight, glyph; double noise;",
             "  int still, batteryLow, dowsed, oneKind, holdKinds, lvl, vi, lastE, ghost, omen, eclipse, fadeE;",
             "  double hearth; int newTonight; double res, coin_; };",
             "static const char* const GrowingKeys[9] = {%s};" % ", ".join('"%s"' % g for g in GROWING),
             "static const V Vectors[] = {"]
    E = K.ENERGIES
    for _ in range(count):
        r, c, nx, res, coin = one(rng)
        rel = r["relics"]
        pad = lambda xs: xs + [0] * (8 - len(xs))
        kinds = sum(1 << E.index(k) for k in r["kinds_tonight"])
        lines.append("  {%d, {%s}, {%s}, {%s}, %d, %s, %s, {%s}, %d, %r, %d, %r, %d, %d, %r, %d, %d, %r, %r, %r, "
                     "%d, %d, %d, %s, %d, %d, %s, %d, %s, %d, %s, %s, %d, %d, %r, %s, %s, %s, %s, %d, %d, %d, %d, %s, "
                     "%d, %d, %d, %r, %d, %.17g, %.17g}," % (
                         len(rel), ", ".join(map(str, pad([RELICS.index(x["id"]) for x in rel]))),
                         ", ".join(map(str, pad([EDS.index(x["ed"]) if x["ed"] else -1 for x in rel]))),
                         ", ".join(map(str, pad([x["tier"] for x in rel]))),
                         CALLINGS.index(r["calling"]), b(r["veil"]), b("pickpocket" in r["trinkets"]),
                         ", ".join(repr(float(r["state"][g])) for g in GROWING), r["hollows_tonight"],
                         r["new_wells"], kinds, r["heat"], r["night"], r["sales"], r["coin"], E.index(r["crown_ban"]),
                         E.index(c["e"]), c["units"], c["price"], c["mult"], c["n"], K.WARDS.index(c["ward"]),
                         FACTIONS.index(c["faction"]), b(c["hidden"]), c["channel"], c["ch11"], b(c["strong"]),
                         c["mesh"], b(c["revisit"]), c["nights_seen"], b(c["new"]), b(c["ward_changed"]),
                         c["wards_tonight"], GLYPHS.index(c["glyph"]) if c["glyph"] else -1, c["noise"],
                         b(c["still"]), b(c["battery_low"]), b(c["dowsed"]), b(c["one_kind"]), c["hold_kinds"],
                         c["lvl"], c["vi"], E.index(c["last_e"]) if c["last_e"] else -1, b(c["ghost"]),
                         OMENS.index(nx["omen"]) if nx["omen"] else -1,
                         ECLS.index(nx["eclipse"]) if nx["eclipse"] else -1, E.index(nx["fade_e"]),
                         float(r["standing"]["hearth"]), r["new_tonight"], res, coin))
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %d sales to %s" % (count, os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
